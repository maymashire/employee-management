/**
 * seed-admin.js — One-time script to create the default Admin user via the
 * Supabase Admin API so the password is hashed with Supabase's own bcrypt.
 *
 * WHY:  Manually inserting a row into auth.users via SQL produces an
 *       incompatible hash → 400 "Invalid login credentials" on sign-in.
 *       This script uses supabase.auth.admin.* which calls the server-side
 *       hasher correctly, fixing the problem permanently.
 *
 * SETUP (one-time):
 *   1. Open Supabase Dashboard → Project Settings → API
 *   2. Copy the "service_role" key  (NOT the anon key)
 *   3. Add this line to your .env.local (already in .gitignore — safe):
 *        SUPABASE_SERVICE_ROLE_KEY=eyJhbGci...
 *   4. Run:  node scripts/seed-admin.js
 */

import { createClient } from '@supabase/supabase-js'
import { readFileSync }  from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

// ── Read .env.local ────────────────────────────────────────────────────────────
const __dir     = dirname(fileURLToPath(import.meta.url))
const envPath   = join(__dir, '..', '.env.local')
const envSource = readFileSync(envPath, 'utf8')

function readEnv(key) {
  const match = envSource.match(new RegExp(`^${key}=(.+)$`, 'm'))
  return match ? match[1].trim() : process.env[key] ?? ''
}

const SUPABASE_URL      = readEnv('VITE_SUPABASE_URL')
const SERVICE_ROLE_KEY  = readEnv('SUPABASE_SERVICE_ROLE_KEY')

if (!SUPABASE_URL || !SERVICE_ROLE_KEY || SERVICE_ROLE_KEY === '') {
  console.error(`
❌  Missing SUPABASE_SERVICE_ROLE_KEY.

Add this to your .env.local file:
  SUPABASE_SERVICE_ROLE_KEY=eyJhbGci...   <-- from Supabase → Project Settings → API

Then re-run:  node scripts/seed-admin.js
`)
  process.exit(1)
}

// ── Admin client (never expose SERVICE_ROLE_KEY to the browser) ───────────────
const admin = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
  auth: { autoRefreshToken: false, persistSession: false },
})

// ── Config ────────────────────────────────────────────────────────────────────
const ADMIN_EMAIL    = 'maryan@gmail.com'
const ADMIN_PASSWORD = '123456'
const ADMIN_ROLE     = 'Admin'           // must match user_role enum in public.users

// ── Main ──────────────────────────────────────────────────────────────────────
async function seed() {
  console.log('\n🚀 EMS Admin Seed Script')
  console.log('─'.repeat(44))

  // 1. Find or create the auth.users record
  let userId

  console.log(`\n[1/3] Checking auth.users for ${ADMIN_EMAIL}…`)
  const { data: { users }, error: listErr } = await admin.auth.admin.listUsers()
  if (listErr) { bail('listUsers failed', listErr); return }

  const existing = users.find(u => u.email === ADMIN_EMAIL)

  if (existing) {
    console.log(`      Found existing user — id: ${existing.id}`)
    console.log(`      Resetting password so Supabase re-hashes it correctly…`)

    const { data: { user }, error: updateErr } =
      await admin.auth.admin.updateUserById(existing.id, {
        password:      ADMIN_PASSWORD,
        email_confirm: true,
      })
    if (updateErr) { bail('updateUserById failed', updateErr); return }
    userId = user.id
    console.log('      ✅ Password updated — bcrypt hash regenerated by Supabase.')

  } else {
    console.log(`      No record found — creating ${ADMIN_EMAIL}…`)
    const { data: { user }, error: createErr } =
      await admin.auth.admin.createUser({
        email:         ADMIN_EMAIL,
        password:      ADMIN_PASSWORD,
        email_confirm: true,   // skip verification email
      })
    if (createErr) { bail('createUser failed', createErr); return }
    userId = user.id
    console.log(`      ✅ Auth user created — id: ${userId}`)
  }

  // 2. Ensure employees row exists (trigger may have already created it)
  console.log('\n[2/3] Ensuring employees record exists…')
  const { data: emp } = await admin
    .from('employees')
    .select('id')
    .eq('id', userId)
    .maybeSingle()

  if (emp) {
    console.log(`      ✅ employees row found — no action needed.`)
  } else {
    const { error: empErr } = await admin.from('employees').insert({
      id:         userId,
      first_name: 'Maryan',
      last_name:  'Admin',
      email:      ADMIN_EMAIL,
      role:       'employee',   // lowercase — satisfies employees_role_check
      status:     'active',
    })
    if (empErr) {
      console.warn(`      ⚠️  Could not insert employees row: ${empErr.message}`)
      console.warn(`         (You can create it manually via the Employees page.)`)
    } else {
      console.log('      ✅ employees row created.')
    }
  }

  // 3. Upsert into public.users (role mapping)
  console.log('\n[3/3] Upserting public.users Admin row…')
  const { error: usersErr } = await admin
    .from('users')
    .upsert(
      { username: ADMIN_EMAIL, role: ADMIN_ROLE, employee_id: userId },
      { onConflict: 'username' },
    )

  if (usersErr) { bail('public.users upsert failed', usersErr); return }
  console.log(`      ✅ public.users row confirmed — role: ${ADMIN_ROLE}`)

  // Done
  console.log('\n' + '─'.repeat(44))
  console.log('🎉 Seed complete!\n')
  console.log(`   Email    : ${ADMIN_EMAIL}`)
  console.log(`   Password : ${ADMIN_PASSWORD}`)
  console.log(`   Role     : ${ADMIN_ROLE}`)
  console.log('\n   Run the dev server and log in:  npm run dev\n')
}

function bail(label, error) {
  console.error(`\n❌ ${label}:`, error.message)
  console.error('   Full error:', error)
}

seed()
