/**
 * Payslip view + print, shared by the Payslips and History tabs.
 * Printing renders standalone HTML into a hidden iframe so only the payslip(s)
 * are printed — not the app chrome around the modal.
 */
import { Printer, Download } from 'lucide-react'
import {
  Modal, ModalHeader, PayBadge, fmt$, fmtMonth, fmtDate, num, grossOf, deductOf, netOf,
  downloadCSV,
} from './shared'
import { companyNow } from '../../context/CompanyContext'


const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))

const slipNo = r => `PS-${(r.pay_period ?? '').slice(0, 7).replace('-', '')}-${(r.id ?? '').slice(0, 5).toUpperCase()}`

function lines(r) {
  return {
    earnings: [
      ['Basic salary', num(r.basic_salary)],
      ['Overtime',     num(r.overtime)],
      ['Bonus',        num(r.bonus)],
    ],
    deductions: [
      ['Deductions', num(r.deductions)],
      ['Tax',        num(r.tax)],
    ],
  }
}

function slipHTML(r, person) {
  const { name: BRAND, tagline } = companyNow()
  const { earnings, deductions } = lines(r)
  const row = ([label, v], neg) =>
    `<tr><td>${esc(label)}</td><td class="amt${neg ? ' neg' : ''}">${neg && v ? '−' : ''}${fmt$(v)}</td></tr>`
  return `
  <section class="slip">
    <header>
      <div><div class="brand">${esc(BRAND)}</div><div class="muted">${esc(tagline)}</div></div>
      <div class="right">
        <div class="eyebrow">Payslip</div>
        <div class="period">${esc(fmtMonth(r.pay_period))}</div>
        <div class="muted">${esc(slipNo(r))}</div>
      </div>
    </header>
    <div class="grid">
      <div><div class="eyebrow">Employee</div><div class="strong">${esc(person.name)}</div>
        <div class="muted">${esc([person.job, person.dept].filter(Boolean).join(' · ') || '—')}</div></div>
      <div class="right"><div class="eyebrow">Status</div><div class="strong">${esc(r.status)}</div>
        <div class="muted">${r.paid_at ? `Paid ${esc(fmtDate(r.paid_at))}` : r.processed_at ? `Processed ${esc(fmtDate(r.processed_at))}` : ''}</div></div>
    </div>
    <div class="cols">
      <table><thead><tr><th>Earnings</th><th class="amt">Amount</th></tr></thead>
        <tbody>${earnings.map(l => row(l)).join('')}</tbody>
        <tfoot><tr><td>Gross pay</td><td class="amt">${fmt$(grossOf(r))}</td></tr></tfoot></table>
      <table><thead><tr><th>Deductions</th><th class="amt">Amount</th></tr></thead>
        <tbody>${deductions.map(l => row(l, true)).join('')}</tbody>
        <tfoot><tr><td>Total deductions</td><td class="amt neg">${deductOf(r) ? '−' : ''}${fmt$(deductOf(r))}</td></tr></tfoot></table>
    </div>
    <div class="net"><span>Net pay</span><strong>${fmt$(netOf(r))}</strong></div>
    ${r.note ? `<p class="note">Note: ${esc(r.note)}</p>` : ''}
    <footer>Generated by ${esc(BRAND)} on ${esc(fmtDate(new Date().toISOString()))}</footer>
  </section>`
}

const PRINT_CSS = `
  *{box-sizing:border-box} body{margin:0;font-family:'Plus Jakarta Sans',Inter,system-ui,sans-serif;color:#0f172a}
  .slip{padding:36px 40px;page-break-after:always;max-width:760px;margin:0 auto}
  .slip:last-child{page-break-after:auto}
  header,.grid{display:flex;justify-content:space-between;gap:24px}
  header{padding-bottom:18px;border-bottom:2px solid #1e3a8a;margin-bottom:20px}
  .brand{font-size:24px;font-weight:800;color:#1e3a8a;letter-spacing:-.02em}
  .right{text-align:right} .muted{font-size:11px;color:#64748b;margin-top:2px}
  .eyebrow{font-size:10px;font-weight:700;color:#94a3b8;text-transform:uppercase;letter-spacing:.12em}
  .period{font-size:16px;font-weight:700;margin-top:2px} .strong{font-size:14px;font-weight:700;margin-top:4px}
  .cols{display:grid;grid-template-columns:1fr 1fr;gap:20px;margin-top:24px}
  table{width:100%;border-collapse:collapse;font-size:12.5px}
  th{text-align:left;font-size:10px;text-transform:uppercase;letter-spacing:.1em;color:#64748b;border-bottom:1px solid #e2e8f0;padding:8px 0}
  td{padding:7px 0;border-bottom:1px solid #f1f5f9} tfoot td{font-weight:700;border-bottom:0;padding-top:10px}
  .amt{text-align:right;font-variant-numeric:tabular-nums} .neg{color:#be123c}
  .net{display:flex;justify-content:space-between;align-items:center;margin-top:24px;padding:16px 20px;border-radius:12px;background:#1e3a8a;color:#fff}
  .net span{font-size:11px;text-transform:uppercase;letter-spacing:.12em;opacity:.8} .net strong{font-size:24px}
  .note{font-size:12px;color:#475569;margin-top:14px}
  footer{margin-top:28px;font-size:10px;color:#94a3b8;text-align:center}
  @page{margin:12mm}
`

export function printPayslips(items) {
  if (!items.length) return
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Payslips</title><style>${PRINT_CSS}</style></head>
    <body>${items.map(({ record, person }) => slipHTML(record, person)).join('')}</body></html>`
  const frame = Object.assign(document.createElement('iframe'), { title: 'print' })
  Object.assign(frame.style, { position: 'fixed', right: '0', bottom: '0', width: '0', height: '0', border: '0' })
  document.body.appendChild(frame)
  const doc = frame.contentWindow.document
  doc.open(); doc.write(html); doc.close()
  setTimeout(() => {
    frame.contentWindow.focus()
    frame.contentWindow.print()
    setTimeout(() => frame.remove(), 1000)
  }, 250)
}

export function payslipCSVRow(r, person) {
  return {
    'Payslip #':  slipNo(r),
    Employee:     person.name,
    Department:   person.dept,
    Period:       fmtMonth(r.pay_period),
    Basic:        num(r.basic_salary),
    Overtime:     num(r.overtime),
    Bonus:        num(r.bonus),
    Gross:        grossOf(r),
    Deductions:   num(r.deductions),
    Tax:          num(r.tax),
    'Net Pay':    netOf(r),
    Status:       r.status,
    'Paid On':    r.paid_at ? fmtDate(r.paid_at) : '',
  }
}

function Line({ label, value, tone = 'text-gray-800', neg }) {
  return (
    <div className="flex justify-between text-sm py-1">
      <span className="text-gray-500">{label}</span>
      <span className={`font-semibold tabular-nums ${tone}`}>{neg && value ? '−' : ''}{fmt$(value)}</span>
    </div>
  )
}

export function PayslipModal({ record: r, person, onClose }) {
  const { earnings, deductions } = lines(r)
  return (
    <Modal onClose={onClose} maxWidth="640px">
      <ModalHeader
        person={person}
        sub={`Payslip · ${fmtMonth(r.pay_period)} · ${slipNo(r)}`}
        onClose={onClose}
      />

      <div className="flex-1 min-h-0 overflow-y-auto px-6 py-5 space-y-5">
        <div className="flex items-start justify-between gap-4">
          <div>
            <p className="text-[11px] font-bold text-gray-400 uppercase tracking-widest">Employee</p>
            <p className="font-bold text-gray-900 mt-1">{person.name}</p>
            <p className="text-xs text-gray-400">{[person.job, person.dept].filter(Boolean).join(' · ') || '—'}</p>
          </div>
          <div className="text-right">
            <PayBadge status={r.status} />
            <p className="text-xs text-gray-400 mt-1.5">
              {r.paid_at ? `Paid ${fmtDate(r.paid_at)}` : r.processed_at ? `Processed ${fmtDate(r.processed_at)}` : `Created ${fmtDate(r.created_at)}`}
            </p>
          </div>
        </div>

        <div className="grid sm:grid-cols-2 gap-4">
          <div className="rounded-xl bg-gray-50 p-4">
            <p className="text-[11px] font-bold text-gray-400 uppercase tracking-widest mb-2">Earnings</p>
            {earnings.map(([label, v]) => <Line key={label} label={label} value={v} />)}
            <div className="border-t border-gray-200 mt-2 pt-2">
              <Line label="Gross pay" value={grossOf(r)} tone="text-emerald-600" />
            </div>
          </div>
          <div className="rounded-xl bg-rose-50/50 p-4">
            <p className="text-[11px] font-bold text-gray-400 uppercase tracking-widest mb-2">Deductions</p>
            {deductions.map(([label, v]) => <Line key={label} label={label} value={v} tone="text-rose-600" neg />)}
            <div className="border-t border-rose-100 mt-2 pt-2">
              <Line label="Total deductions" value={deductOf(r)} tone="text-rose-600" neg />
            </div>
          </div>
        </div>

        <div className="flex items-center justify-between rounded-2xl px-5 py-4 text-white bg-gradient-to-br from-[#1e3a8a] to-indigo-900 shadow-lg">
          <div>
            <p className="text-[11px] font-semibold text-indigo-200 uppercase tracking-widest">Net pay</p>
            <p className="text-xs text-indigo-200 mt-0.5">{fmtMonth(r.pay_period)}</p>
          </div>
          <p className="text-3xl font-extrabold tracking-tight tabular-nums">{fmt$(netOf(r))}</p>
        </div>

        {r.note && (
          <p className="text-xs text-gray-500 bg-gray-50 rounded-xl px-3 py-2.5"><b className="text-gray-600">Note:</b> {r.note}</p>
        )}
      </div>

      <div className="flex items-center justify-end gap-2 px-6 py-4 border-t border-gray-100 shrink-0">
        <button onClick={() => downloadCSV([payslipCSVRow(r, person)], `${slipNo(r)}.csv`)}
          className="flex items-center gap-1.5 px-4 py-2 rounded-xl text-sm font-semibold text-gray-600 hover:bg-gray-100 transition-colors">
          <Download size={14} /> CSV
        </button>
        <button onClick={() => printPayslips([{ record: r, person }])}
          className="flex items-center gap-2 px-5 py-2 rounded-xl text-sm font-semibold text-white bg-[#1e3a8a] hover:bg-[#162d6e] transition-colors">
          <Printer size={14} /> Print
        </button>
      </div>
    </Modal>
  )
}
