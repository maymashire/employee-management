/**
 * Payslips — lists payroll_records where status IN ('Processing', 'Paid').
 * Employee name/department from employee_salary_config via salary_config_id FK.
 * net_salary is a GENERATED column (no need to compute it client-side).
 */
import { useState, useEffect } from 'react'
import { supabase } from '../../lib/supabaseClient'
import { FileText, Eye, Printer, X, Loader2, Search } from 'lucide-react'

const fmt$ = n => `$${Number(n ?? 0).toFixed(2)}`

const fmtPeriod = iso =>
  iso ? new Date(`${iso}T00:00:00`).toLocaleDateString('en-US', { month: 'long', year: 'numeric' }) : '—'

const fmtDate = iso =>
  iso ? new Date(`${iso}T00:00:00`).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }) : '—'

const fmtDateShort = iso =>
  iso ? new Date(iso).toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' }) : '—'

function initials(name = '') {
  return name.trim().split(/\s+/).map(w => w[0] ?? '').join('').slice(0, 2).toUpperCase()
}

// ── Payslip print modal ────────────────────────────────────────────────────────
function PayslipModal({ record, onClose }) {
  if (!record) return null

  const cfg   = record.employee_salary_config
  const name  = cfg?.employee_name         ?? '—'
  const dept  = cfg?.department             ?? '—'
  const email = cfg?.employees?.email       ?? null
  const basic = Number(record.basic_salary ?? 0)
  const ot    = Number(record.overtime     ?? 0)
  const bonus = Number(record.bonus        ?? 0)
  const dedu  = Number(record.deductions   ?? 0)
  const tax   = Number(record.tax          ?? 0)
  // net_salary is GENERATED by DB; fall back to formula if null (shouldn't happen)
  const net   = Number(record.net_salary ?? (basic + ot + bonus - dedu - tax))
  const gross = basic + ot + bonus

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4">
      <div className="bg-white rounded-2xl shadow-2xl w-full max-w-2xl max-h-[92vh] overflow-y-auto">

        {/* Toolbar */}
        <div className="sticky top-0 flex items-center justify-between px-6 py-3.5 border-b border-gray-100 bg-white rounded-t-2xl z-10">
          <h2 className="font-bold text-gray-900">Pay Statement</h2>
          <div className="flex items-center gap-2">
            <button onClick={() => window.print()}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-gray-600 border border-gray-200 rounded-lg hover:bg-gray-50 transition-colors">
              <Printer size={13} /> Print
            </button>
            <button onClick={onClose} className="p-1.5 rounded-lg hover:bg-gray-100 text-gray-400">
              <X size={17} />
            </button>
          </div>
        </div>

        <div className="p-8 space-y-6">

          {/* Company + period header */}
          <div className="flex justify-between items-start">
            <div>
              <p className="text-2xl font-extrabold text-[#1e3a8a] tracking-tight">VibeHR</p>
              <p className="text-xs text-gray-400">Better Culture, Better Work.</p>
            </div>
            <div className="text-right">
              <p className="text-xs text-gray-400 uppercase tracking-wider">Pay Period</p>
              <p className="font-bold text-gray-800 mt-0.5">{fmtPeriod(record.pay_period)}</p>
              <span className={`mt-1 inline-flex px-2.5 py-0.5 rounded-full text-xs font-semibold
                ${record.status === 'Paid' ? 'bg-emerald-100 text-emerald-700' : 'bg-amber-100 text-amber-700'}`}>
                {record.status}
              </span>
            </div>
          </div>

          <div className="border-t border-gray-100" />

          {/* Employee info */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-6">
            <div>
              <p className="text-xs font-semibold text-gray-400 uppercase tracking-wider mb-2">Employee</p>
              <div className="flex items-center gap-3">
                <div className="w-11 h-11 rounded-full bg-indigo-100 flex items-center justify-center shrink-0">
                  <span className="text-sm font-bold text-indigo-600">{initials(name)}</span>
                </div>
                <div>
                  <p className="font-bold text-gray-900">{name}</p>
                  <p className="text-xs text-gray-500">{dept}</p>
                  {email && <p className="text-xs text-gray-400">{email}</p>}
                </div>
              </div>
            </div>
            <div>
              <p className="text-xs font-semibold text-gray-400 uppercase tracking-wider mb-2">Payment Info</p>
              <p className="text-sm text-gray-700">Period: <span className="font-medium">{fmtPeriod(record.pay_period)}</span></p>
              {record.processed_at && (
                <p className="text-sm text-gray-700 mt-0.5">Processed: <span className="font-medium">{fmtDateShort(record.processed_at)}</span></p>
              )}
            </div>
          </div>

          {/* Earnings table */}
          <div className="bg-gray-50 rounded-xl p-5 space-y-2.5">
            <p className="text-xs font-semibold text-gray-500 uppercase tracking-wider mb-3">Earnings</p>
            {[
              { label: 'Basic Salary',  amount: basic, cls: 'text-gray-900' },
              { label: 'Overtime',      amount: ot,    cls: 'text-green-700' },
              { label: 'Bonus',         amount: bonus, cls: 'text-purple-700' },
            ].map(({ label, amount, cls }) => (
              <div key={label} className="flex justify-between text-sm">
                <span className="text-gray-600">{label}</span>
                <span className={`font-semibold ${cls}`}>{fmt$(amount)}</span>
              </div>
            ))}
            <div className="border-t border-gray-200 pt-2.5 flex justify-between text-sm font-bold">
              <span className="text-gray-700">Gross Pay</span>
              <span className="text-emerald-700">{fmt$(gross)}</span>
            </div>
          </div>

          {/* Deductions table */}
          {(dedu > 0 || tax > 0) && (
            <div className="bg-red-50/60 rounded-xl p-5 space-y-2.5">
              <p className="text-xs font-semibold text-gray-500 uppercase tracking-wider mb-3">Deductions</p>
              {dedu > 0 && (
                <div className="flex justify-between text-sm">
                  <span className="text-gray-600">Deductions</span>
                  <span className="font-semibold text-red-600">-{fmt$(dedu)}</span>
                </div>
              )}
              {tax > 0 && (
                <div className="flex justify-between text-sm">
                  <span className="text-gray-600">Tax</span>
                  <span className="font-semibold text-orange-600">-{fmt$(tax)}</span>
                </div>
              )}
              <div className="border-t border-red-100 pt-2.5 flex justify-between text-sm font-bold">
                <span className="text-gray-700">Total Deductions</span>
                <span className="text-red-600">-{fmt$(dedu + tax)}</span>
              </div>
            </div>
          )}

          {/* Net pay banner */}
          <div className="flex justify-between items-center bg-[#1e3a8a] text-white rounded-xl px-6 py-5">
            <div>
              <p className="text-xs text-blue-300 uppercase tracking-wider">Net Pay</p>
              <p className="text-xs text-blue-300 mt-0.5">{fmtPeriod(record.pay_period)}</p>
            </div>
            <p className="text-3xl font-extrabold tracking-tight">{fmt$(net)}</p>
          </div>

          <p className="text-center text-xs text-gray-300">Generated by VibeHR</p>
        </div>
      </div>
    </div>
  )
}

// ── Main ───────────────────────────────────────────────────────────────────────
export default function Payslips() {
  const [records,  setRecords]  = useState([])
  const [loading,  setLoading]  = useState(true)
  const [selected, setSelected] = useState(null)
  const [search,   setSearch]   = useState('')

  useEffect(() => {
    const WITH_EMP = `
      id, pay_period, basic_salary, overtime, bonus,
      deductions, tax, net_salary, status, processed_at,
      employee_salary_config!salary_config_id(
        employee_name, department, employee_id,
        employees!employee_salary_config_employee_id_fkey(id, first_name, last_name, email)
      )`

    const WITHOUT_EMP = `
      id, pay_period, basic_salary, overtime, bonus,
      deductions, tax, net_salary, status, processed_at,
      employee_salary_config!salary_config_id(employee_name, department, employee_id)`

    supabase
      .from('payroll_records')
      .select(WITH_EMP)
      .in('status', ['Processing', 'Paid'])
      .order('pay_period', { ascending: false })
      .then(async ({ data, error }) => {
        if (error?.message?.toLowerCase().includes('relationship')) {
          const res = await supabase
            .from('payroll_records')
            .select(WITHOUT_EMP)
            .in('status', ['Processing', 'Paid'])
            .order('pay_period', { ascending: false })
          setRecords(res.data ?? [])
        } else {
          setRecords(data ?? [])
        }
        setLoading(false)
      })
  }, [])

  const filtered = records.filter(r => {
    const q = search.toLowerCase()
    if (!q) return true
    const cfg = r.employee_salary_config
    return (cfg?.employee_name ?? '').toLowerCase().includes(q) ||
           (cfg?.department    ?? '').toLowerCase().includes(q)
  })

  if (loading) {
    return (
      <div className="flex items-center justify-center py-24 gap-3 text-gray-400">
        <Loader2 size={22} className="animate-spin text-blue-600" />
        <span className="text-sm">Loading payslips…</span>
      </div>
    )
  }

  if (records.length === 0) {
    return (
      <div className="bg-white rounded-2xl border border-gray-100 shadow-sm flex flex-col items-center justify-center py-24 gap-3 text-gray-400">
        <FileText size={40} className="text-gray-200" />
        <p className="text-sm font-medium text-center">
          No payslips available yet.<br />Generate payroll and advance status to Processing or Paid.
        </p>
      </div>
    )
  }

  return (
    <div className="space-y-4">

      {/* Search */}
      <div className="relative max-w-sm">
        <Search size={15} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-gray-400 pointer-events-none" />
        <input
          value={search}
          onChange={e => setSearch(e.target.value)}
          placeholder="Search employee or department…"
          className="w-full pl-9 pr-4 py-2.5 rounded-xl border border-gray-200 bg-white text-sm
            focus:outline-none focus:ring-2 focus:ring-[#1e3a8a]/20 focus:border-[#1e3a8a] transition-colors"
        />
      </div>

      {/* Table */}
      <div className="bg-white rounded-2xl border border-gray-100 shadow-sm overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-sm min-w-[680px]">
            <thead>
              <tr className="border-b border-gray-100 bg-gray-50/60">
                {['Employee','Department','Pay Period','Net Salary','Status',''].map(h => (
                  <th key={h} className="px-5 py-4 text-left text-[11px] font-semibold text-gray-400 uppercase tracking-wider">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-50">
              {filtered.map(r => {
                const cfg  = r.employee_salary_config
                const name = cfg?.employee_name ?? '—'
                const ini  = initials(name)
                return (
                  <tr key={r.id} className="hover:bg-gray-50/40 transition-colors">
                    <td className="px-5 py-4">
                      <div className="flex items-center gap-3">
                        <div className="w-9 h-9 rounded-full bg-indigo-100 flex items-center justify-center shrink-0">
                          <span className="text-xs font-bold text-indigo-600">{ini}</span>
                        </div>
                        <p className="font-semibold text-gray-800">{name}</p>
                      </div>
                    </td>
                    <td className="px-5 py-4 text-gray-500">{cfg?.department ?? '—'}</td>
                    <td className="px-5 py-4 text-gray-500 text-xs">{fmtPeriod(r.pay_period)}</td>
                    {/* net_salary is GENERATED by DB */}
                    <td className="px-5 py-4 font-bold text-gray-900">{fmt$(r.net_salary)}</td>
                    <td className="px-5 py-4">
                      <span className={`inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-semibold
                        ${r.status === 'Paid' ? 'bg-emerald-100 text-emerald-700' : 'bg-amber-100 text-amber-700'}`}>
                        {r.status}
                      </span>
                    </td>
                    <td className="px-5 py-4">
                      <button onClick={() => setSelected(r)}
                        className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-[#1e3a8a]
                          border border-[#1e3a8a]/25 rounded-lg hover:bg-[#1e3a8a]/5 transition-colors">
                        <Eye size={13} /> View
                      </button>
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </div>
      </div>

      {selected && <PayslipModal record={selected} onClose={() => setSelected(null)} />}
    </div>
  )
}
